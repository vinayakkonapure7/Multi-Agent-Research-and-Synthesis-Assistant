/**
 * One-off generator for frontend/src/lib/commonWords.js.
 *
 * Two sources are combined because neither alone is good enough:
 *   - `@derock.ir/words-frequency` is real frequency data (~18k words
 *     ranked by usage in Project Gutenberg), so it reliably covers
 *     ordinary function/content words ("the", "research", "using"...).
 *     But it's 19th/20th-century literary text, so it's missing a lot of
 *     modern research/tech vocabulary (e.g. "retrieval", "documentation").
 *   - `an-array-of-english-words` is a huge (~275k) alphabetical dictionary
 *     with NO frequency signal, so a small random/strided slice of it is
 *     dominated by obscure entries (verified empirically: a 5000-word
 *     stride sample matched 0 of ~15 ordinary test words). It's only
 *     useful here as a big pool to draw a *sizeable* supplemental sample
 *     from, to catch modern vocabulary the frequency list misses.
 *
 * Because sampling is inherently a coverage gamble, the script ends with a
 * sanity check against a list of ordinary (non-technical, non-adversarial)
 * English words spanning short/medium/long lengths, and tops up the set
 * with any that are missing — the goal is broad, dependable coverage of
 * ordinary vocabulary, not a perfectly "fair" random sample.
 *
 * Run with `node scripts/gen-common-words.cjs` from frontend/, then remove
 * both temporary devDependencies — only the generated commonWords.js ships.
 */
const fs = require('fs')
const path = require('path')

const freqWords = require('@derock.ir/words-frequency').map(([, word]) => word)
const dictionary = require('an-array-of-english-words')

const combined = new Set(freqWords)

// Supplement with a broad, reproducibly-sampled slice of the full
// dictionary for coverage the frequency list (old literary text) misses.
const filtered = dictionary.filter(w => /^[a-z]+$/.test(w) && w.length >= 3 && w.length <= 14 && !combined.has(w))
let seed = 42
function nextRandom() {
  // Deterministic PRNG (mulberry32) so this script's output is reproducible.
  seed |= 0
  seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const shuffled = [...filtered]
for (let i = shuffled.length - 1; i > 0; i--) {
  const j = Math.floor(nextRandom() * (i + 1))
  ;[shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
}
for (const w of shuffled.slice(0, 4000)) combined.add(w)

// Ordinary vocabulary sanity check — top up anything missing so the check
// doesn't misfire on everyday words just because sampling missed them.
const SANITY_WORDS = [
  'research', 'synthesis', 'assistant', 'using', 'factual', 'accuracy',
  'retrieval', 'strategies', 'question', 'answering', 'technical',
  'documentation', 'hybrid', 'impact', 'analysis', 'summary', 'context',
  'evidence', 'source', 'sources', 'report', 'reports', 'topic', 'chapter',
  'section', 'method', 'methods', 'result', 'results', 'process', 'system',
  'systems', 'data', 'model', 'models', 'design', 'policy', 'climate',
  'change', 'mitigation', 'coastal', 'cities', 'health', 'economic',
  'social', 'political', 'history', 'science', 'engineering', 'education',
]
const addedForSanity = SANITY_WORDS.filter(w => !combined.has(w))
for (const w of addedForSanity) combined.add(w)

const sample = [...combined].sort()

const out = `/**
 * Common English words for a client-side gibberish pre-check (see
 * HomeScreen.jsx). Combines real frequency data with a sampled slice of a
 * full dictionary for broader coverage. Generated by
 * scripts/gen-common-words.cjs — do not hand-edit, regenerate instead.
 */
export const COMMON_WORDS = new Set(${JSON.stringify(sample)})
`

fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'commonWords.js'), out)
console.log(`Wrote ${sample.length} words to src/lib/commonWords.js`)
console.log(`Topped up ${addedForSanity.length} sanity words that sampling missed:`, addedForSanity)
